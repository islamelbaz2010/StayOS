"""Admin Reports catalog — the single registry of reportable datasets.

Every entry declares: the category (catalog grouping), the columns the
builder returns (frontend translates ``adminReports.columns.<key>``),
which of the shared filter params the report honours, which columns are
server-sortable, which money columns roll into the totals row, and the
canonical ``date_basis`` (reported to the UI so date filters are never
ambiguous). ``implemented=False`` entries appear in the catalog disabled
with a reason — no fake reports.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ReportDef:
    key: str
    category: str
    builder: str
    columns: tuple[str, ...]
    date_basis: str
    filters: tuple[str, ...] = ()
    sortable: tuple[str, ...] = ()
    default_sort: str = "created_at"
    money_columns: tuple[str, ...] = ()
    implemented: bool = True
    unavailable_reason: str | None = None
    fixed: dict = field(default_factory=dict)


